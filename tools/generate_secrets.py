"""Generate a fresh, independent set of MarosimGo secrets into a private file.

Values are written to OUTPUT (created with mode 0600, never overwritten) and are NOT printed, so
they do not end up in terminal scrollback, CI logs or chat. Run it on the server that will use them,
then copy the lines you need into backend/.env (see docs/SECURITY_INCIDENT_RESPONSE.md for the
order: encryption keys go FIRST in their list, the old key stays second until
`manage.py rotate_encryption_keys --apply` has run).

    python tools/generate_secrets.py backend/.env.new-secrets

Requires only the `cryptography` package (already a backend dependency). Does not touch Django.
"""

import argparse
import os
import secrets
import sys
from pathlib import Path

from cryptography.fernet import Fernet

ROTATING = "NEW key; append ',<old key>' while rotating"

SECRETS = {
    # name: (generator, comment)
    "DJANGO_SECRET_KEY": (lambda: secrets.token_urlsafe(50), "Django signing"),
    "JWT_SIGNING_KEY": (lambda: secrets.token_urlsafe(50), "API tokens (must differ from DJANGO_SECRET_KEY)"),
    "PINFL_HASH_KEY": (lambda: secrets.token_urlsafe(50), "PINFL / invitation blind index (HMAC)"),
    "PINFL_ENCRYPTION_KEYS": (lambda: Fernet.generate_key().decode(), ROTATING),
    "GOOGLE_TOKEN_ENCRYPTION_KEY": (lambda: Fernet.generate_key().decode(), ROTATING),
}


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("output", type=Path, help="file to create (must not exist)")
    args = parser.parse_args(argv)

    values = {name: make() for name, (make, _) in SECRETS.items()}
    if values["DJANGO_SECRET_KEY"] == values["JWT_SIGNING_KEY"]:  # astronomically unlikely
        return main(argv)

    lines = ["# Generated by tools/generate_secrets.py. Keep private; delete after use.", ""]
    for name, (_, comment) in SECRETS.items():
        lines += [f"# {comment}", f"{name}={values[name]}", ""]

    try:
        # O_EXCL: never overwrite; 0o600: readable by the owner only, from the first byte on.
        fd = os.open(args.output, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    except FileExistsError:
        print(f"{args.output} already exists; refusing to overwrite it.", file=sys.stderr)
        return 1
    with os.fdopen(fd, "w") as handle:
        handle.write("\n".join(lines))

    print(f"Wrote {len(values)} new secrets to {args.output} (mode 600). Values are not shown:")
    for name in values:
        print(f"  {name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
